async function runTests() {
  console.log("🧪 Starting Inventory Flow Tests...\n");

  try {
    // Create test image
    const imagePath = createTestImage();
    console.log("✅ Test image created");

    // Step 1: Create Truck
    console.log("\n📦 Step 1: Creating truck...");
    const truckResponse = await axios.post(`${API_URL}/trucks`, testTruck);
    const truckId = truckResponse.data.data.id;
    console.log(`✅ Truck created with ID: ${truckId}`);

    // Step 2: Add Position with Image
    console.log("\n📝 Step 2: Adding position with image...");
    const form = new FormData();
    form.append("truck_id", truckId);
    form.append("name", testPosition.name);
    form.append("variety", testPosition.variety);
    form.append("quantity", testPosition.quantity);
    form.append("price", testPosition.price);
    form.append("notes", testPosition.notes);
    form.append("photo", fs.createReadStream(imagePath), "test-image.jpg");

    const positionResponse = await axios.post(
      `${API_URL}/inventory-items`,
      form,
      {
        headers: form.getHeaders(),
      },
    );

    const itemId = positionResponse.data.data.id;
    const photoUrl = positionResponse.data.data.photo_url;
    console.log(`✅ Position created with ID: ${itemId}`);
    console.log(`✅ Photo URL: ${photoUrl}`);

    // Step 3: Retrieve Item from DB
    console.log("\n🔍 Step 3: Retrieving item from truck...");
    const itemsResponse = await axios.get(
      `${API_URL}/inventory-items/truck/${truckId}`,
    );
    const items = itemsResponse.data.data;
    const savedItem = items.find((i) => i.id === itemId);

    if (savedItem) {
      console.log("✅ Item found in database:");
      console.log(`   - Name: ${savedItem.name}`);
      console.log(`   - Variety: ${savedItem.variety}`);
      console.log(`   - Price: ${savedItem.price}`);
      console.log(`   - Quantity: ${savedItem.quantity}`);
      console.log(`   - Photo URL: ${savedItem.photo_url}`);
      console.log(`   - Notes: ${savedItem.notes}`);

      // Validate data
      if (
        savedItem.name === testPosition.name &&
        savedItem.price === testPosition.price &&
        savedItem.quantity === testPosition.quantity
      ) {
        console.log("\n✅ All data validated successfully!");
      } else {
        console.log("\n❌ Data mismatch detected!");
      }
    } else {
      console.log("❌ Item not found in database!");
    }

    // Step 4: Check image path
    console.log("\n📸 Step 4: Checking image storage...");
    const uploadsDir = path.join(__dirname, "../public/uploads");
    const imageFileName = path.basename(photoUrl);
    const imagePath2 = path.join(uploadsDir, imageFileName);

    if (fs.existsSync(imagePath2)) {
      const stats = fs.statSync(imagePath2);
      console.log(`✅ Image file exists at: ${imagePath2}`);
      console.log(`✅ File size: ${stats.size} bytes`);
    } else {
      console.log(`❌ Image file not found at: ${imagePath2}`);
    }

    console.log("\n🎉 All tests completed!");
  } catch (error) {
    console.error("\n❌ Test failed:", error.response?.data || error.message);
  } finally {
    // Cleanup
    const tempImagePath = path.join(__dirname, "test-image-temp.jpg");
    if (fs.existsSync(tempImagePath)) {
      fs.unlinkSync(tempImagePath);
    }
  }
}

runTests();
